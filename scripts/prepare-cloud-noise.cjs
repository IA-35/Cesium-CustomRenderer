// Bake the pinned MIT Perlin-Worley reference into the existing padded 64^3 atlas.
// Generation is offline; the render loop only uploads the prepared bytes.
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const reference = path.join(root, 'src/environment/reference/three-clouds')
const read = name => fs.readFileSync(path.join(reference, name), 'utf8')
const shape = read('cloudShape.frag')
const detail = read('cloudShapeDetail.frag')
const detailFunction = detail.slice(detail.indexOf('void main()'))
  .replace('void main()', 'float cloudDetail(vec3 point)')
  .replace('vec3 point = vec3(vUv.x, vUv.y, layer);', '')
  .replace('outputColor =', 'return')
const shader = ['#version 300 es', 'precision highp float; precision highp int;',
  'out vec4 color;',
  'float remap(float v, float a, float b) { return (v-a)/(b-a); }',
  'float remap(float v, float a, float b, float c, float d) { return mix(c,d,remap(v,a,b)); }',
  read('perlin.glsl'), read('tileableNoise.glsl'),
  shape.slice(shape.indexOf('float getPerlinWorley'), shape.indexOf('void main()')),
  detailFunction,
  `void main() {
    ivec2 pixel = ivec2(gl_FragCoord.xy);
    ivec2 tile = pixel / 66;
    vec2 xy = mod(vec2(pixel % 66 - 1), 64.0) / 64.0;
    vec3 p = vec3(xy, float(tile.y * 8 + tile.x) / 64.0);
    float broad = remap(getPerlinWorley(p), getWorleyFbm(p) - 1.0, 1.0);
    color = vec4(broad, cloudDetail(p), 0.5 + 0.5 * getPerlinNoise(p, 4.0, 3), 1.0);
  }`].join('\n')
const vertex = '#version 300 es\nvoid main(){vec2 p=vec2((gl_VertexID<<1)&2,gl_VertexID&2);gl_Position=vec4(p*2.-1.,0.,1.);}'
const html = `<!doctype html><canvas width="528" height="528"></canvas><script>
try {
  const gl = document.querySelector('canvas').getContext('webgl2');
  if (!gl) throw new Error('WebGL2 unavailable');
  const compile = (type, source) => {
    const s = gl.createShader(type); gl.shaderSource(s, source); gl.compileShader(s);
    if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(s));
    return s;
  };
  const program = gl.createProgram();
  gl.attachShader(program, compile(gl.VERTEX_SHADER, ${JSON.stringify(vertex)}));
  gl.attachShader(program, compile(gl.FRAGMENT_SHADER, ${JSON.stringify(shader)}));
  gl.linkProgram(program);
  if (!gl.getProgramParameter(program, gl.LINK_STATUS)) throw new Error(gl.getProgramInfoLog(program));
  gl.useProgram(program); gl.disable(gl.DITHER); gl.drawArrays(gl.TRIANGLES, 0, 3);
  const bytes = new Uint8Array(528 * 528 * 4);
  gl.readPixels(0, 0, 528, 528, gl.RGBA, gl.UNSIGNED_BYTE, bytes);
  if (gl.getError() !== gl.NO_ERROR) throw new Error('Atlas readback failed');
  let text = ''; for (let i=0;i<bytes.length;i+=8192) text += String.fromCharCode(...bytes.subarray(i,i+8192));
  window.result = { data: btoa(text) };
} catch(error) { window.result = { error: String(error) }; }
</script>`

async function main() {
  const { chromium } = require(process.env.CESIUM_PLAYWRIGHT || 'playwright')
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage()
    // No scene, services, external assets, or GPU state belonging to Cesium is touched.
    await page.setContent(html)
    await page.waitForFunction(() => window.result)
    const result = await page.evaluate(() => window.result)
    if (result.error) throw new Error(result.error)
    const header = '// Generated by scripts/prepare-cloud-noise.cjs. Do not edit.\n'
      + '// three-geospatial b012ad06: Shota Matsuda (2024), Sebastien Hillaire (2017),\n'
      + '// G-Truc Creation (2005). MIT licences are retained in reference/three-clouds.\n'
    fs.writeFileSync(path.join(root, 'src/environment/cloudNoiseData.js'), header
      + `export default Uint8Array.from(atob('${result.data}'), c => c.charCodeAt(0))\n`)
    console.log(JSON.stringify({ bytes: Buffer.from(result.data, 'base64').length, size: [528, 528] }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
