// Generates the procedural grass species GLBs and the bundled data-URL module.
//
// Usage: node scripts/prepare-grass-species.cjs
// Output:
//   vendor/cesium-ez-tree/assets/models/grass-species/<species>.glb  (inspection / server hosting)
//   src/instances/grassSpeciesAssets.js                              (embedded in CCR.min.js)
//
// The assets are deterministic: rerunning produces byte-identical files.
const fs = require('node:fs')
const path = require('node:path')
const { createGrassAtlas } = require('./grass-species/atlas.cjs')
const { SPECIES_MESHES } = require('./grass-species/meshes.cjs')
const { encodeGrayAlphaPng, writeGlb } = require('./grass-species/encoders.cjs')

const root = path.resolve(__dirname, '..')
const modelDirectory = path.join(root, 'vendor/cesium-ez-tree/assets/models/grass-species')
const moduleFile = path.join(root, 'src/instances/grassSpeciesAssets.js')
const ALPHA_CUTOFF = 0.35

function prepareGrassSpecies() {
  const atlas = createGrassAtlas()
  const png = encodeGrayAlphaPng(atlas.width, atlas.height, atlas.pixels)
  fs.mkdirSync(modelDirectory, { recursive: true })
  const urls = {}
  const summary = {}
  for (const [species, create] of Object.entries(SPECIES_MESHES)) {
    const mesh = create()
    const glb = writeGlb(mesh, png, { name: `grass-${species}`, alphaCutoff: ALPHA_CUTOFF })
    fs.writeFileSync(path.join(modelDirectory, `${species}.glb`), glb)
    urls[species] = `data:model/gltf-binary;base64,${glb.toString('base64')}`
    summary[species] = { triangles: mesh.indices.length / 3, vertices: mesh.positions.length / 3, bytes: glb.length }
  }
  const lines = [
    '// Generated by scripts/prepare-grass-species.cjs. Do not edit by hand.',
    '// Procedural grass species GLBs (shared gray+alpha atlas), embedded so the',
    '// bundle needs no extra deployed model files.',
    `export const GRASS_SPECIES_SUMMARY = Object.freeze(${JSON.stringify(summary)})`,
    'export const GRASS_SPECIES_ASSET_URLS = Object.freeze({',
    ...Object.entries(urls).map(([species, url]) => `  ${species}: '${url}',`),
    '})',
    '',
  ]
  fs.writeFileSync(moduleFile, lines.join('\n'))
  return summary
}

if (require.main === module) console.log(JSON.stringify(prepareGrassSpecies(), null, 2))

module.exports = { prepareGrassSpecies }
