// Compile the pinned MIT upstream modules against the host's Cesium namespace.
// No Cesium implementation is bundled; the factory also works with injected engines.
const fs=require('node:fs'),path=require('node:path'),webpack=require('webpack')
const root=path.resolve(__dirname,'..'),vendor=path.join(root,'vendor/cesium-ez-tree')
const compiler=webpack({mode:'none',devtool:false,context:root,
  entry:path.join(vendor,'src/ccr-entry.js'),
  output:{path:path.join(root,'build/.generated/eztree'),filename:'factory.cjs',library:{name:'EzTreeModule',type:'var'}},
  externalsType:'var',externals:[({request},callback)=>{
    if(request?.startsWith('@cesium/engine/Source/'))return callback(null,'Cesium.'+path.basename(request,'.js'))
    callback()
  }],optimization:{minimize:false},performance:{hints:false}})
compiler.run((error,stats)=>{
  compiler.close(()=>{})
  if(error||stats.hasErrors()){console.error(error||stats.toString({all:false,errors:true}));process.exitCode=1;return}
  const code=fs.readFileSync(path.join(root,'build/.generated/eztree/factory.cjs'),'utf8')
  fs.writeFileSync(path.join(vendor,'runtime.js'),`// Generated by scripts/build-eztree-runtime.cjs. See LICENSE, NOTICE.md, CCR_PATCHES.md.\nconst runtimes=new WeakMap();\nexport default function getEzTreeRuntime(Cesium){\nif(runtimes.has(Cesium))return runtimes.get(Cesium);\n${code}\nruntimes.set(Cesium,EzTreeModule);return EzTreeModule;\n}\n`)
  console.log('cesium-ez-tree runtime built (external Cesium)')
})
